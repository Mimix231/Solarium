#!/usr/bin/env node
'use strict';
/** Deterministic registry of trusted Graph V2 executable blocks. Catalog/draft entries never enter this list. */
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
let ts;
try { ts = require('typescript'); }
catch { ts = require(path.join(execFileSync('npm', ['root', '-g'], { encoding:'utf8' }).trim(), 'typescript')); }
const root = path.resolve(__dirname, '..');
const blocks = path.join(root, 'src/spica/runtime/blocks');
const output = path.join(root, 'src/spica/runtime/registry.generated.ts');
const check = process.argv.includes('--check');
const fail = message => { throw Error(`SPICA V2 registry: ${message}`); };
const files = [];
function scan(folder) {
  for (const item of fs.readdirSync(folder, { withFileTypes:true }).sort((a,b)=>a.name.localeCompare(b.name))) {
    const filename = path.join(folder,item.name);
    if (item.isDirectory()) {
      if (folder === blocks) {
        const runtimeRoot = path.join(filename,'runtime');
        if (fs.existsSync(runtimeRoot) && fs.statSync(runtimeRoot).isDirectory()) scan(runtimeRoot);
      } else scan(filename);
    }
    else if (folder !== blocks && item.isFile() && item.name.endsWith('.ts') && !item.name.endsWith('.test.ts')) files.push(filename);
  }
}
scan(blocks);
if (!files.length) fail('No executable blocks were found.');
const seen = new Set();
const imports = [];
const references = [];
for (const [index,filename] of files.entries()) {
  const relative=path.relative(blocks,filename).replaceAll(path.sep,'/');
  if (relative.split('/').length < 3 || relative.split('/')[1] !== 'runtime') fail(`Expected category/runtime/file.ts: ${relative}`);
  const parsed=ts.createSourceFile(filename,fs.readFileSync(filename,'utf8'),ts.ScriptTarget.Latest,true,ts.ScriptKind.TS);
  if (parsed.parseDiagnostics.length) fail(`Cannot parse ${relative}: ${parsed.parseDiagnostics[0].messageText}`);
  const exports=parsed.statements.filter(ts.isExportAssignment);
  if (exports.length!==1 || exports[0].isExportEquals || !ts.isCallExpression(exports[0].expression) ||
      !ts.isIdentifier(exports[0].expression.expression) || exports[0].expression.expression.text!=='defineRuntimeBlock' ||
      exports[0].expression.arguments.length!==1 || !ts.isObjectLiteralExpression(exports[0].expression.arguments[0])) {
    fail(`Exactly one export default defineRuntimeBlock({...}) required in ${relative}`);
  }
  const properties=new Map(exports[0].expression.arguments[0].properties.map(prop => [prop.name?.getText(parsed),prop]));
  const str = name => {
    const property=properties.get(name);
    if (!property || !ts.isPropertyAssignment(property) || !ts.isStringLiteral(property.initializer))
      fail(`Static ${name} string required in ${relative}`);
    return property.initializer.text;
  };
  const id=str('id'), version=str('version'), trust=str('trust');
  const name=path.basename(filename,'.ts');
  if (!/^spica\.runtime\.[a-z][a-z0-9_]*$/.test(id) || name!==id.slice('spica.runtime.'.length).replaceAll('_','-') || version!=='1' || trust!=='built-in') {
    fail(`Block filename/ID/version/trust mismatch: ${relative}`);
  }
  const signature=`${id}@${version}`;
  if (seen.has(signature))fail(`Duplicate block ${signature}`);
  seen.add(signature);
  const symbol=`adapter${index}`;
  imports.push(`import ${symbol} from './blocks/${relative.slice(0,-3)}';`);
  references.push(`  ${symbol},`);
}
const generated=[
  '/** AUTO-GENERATED by scripts/generate-spica-runtime-registry.cjs. Do not edit manually. */',
  "import type { SpicaBlockAdapter } from './adapter';", ...imports, '',
  'export const generatedRuntimeAdapters: readonly SpicaBlockAdapter[] = [', ...references, '];', '',
].join('\n');
if (check) {
  if (!fs.existsSync(output) || fs.readFileSync(output,'utf8')!==generated) fail('Stale generated registry; run node scripts/generate-spica-runtime-registry.cjs.');
  process.stdout.write(`SPICA V2 runtime registry verified: ${files.length} executable modules.\n`);
} else {
  fs.writeFileSync(output,generated);
  process.stdout.write(`SPICA V2 runtime registry generated: ${files.length} executable modules.\n`);
}
