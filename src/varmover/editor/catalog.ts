const EXPERIMENTAL_COMPONENTS = new Set<ComponentType>([
  "ambient-light-2d", "light-occluder-2d", "weather-zone", "navigation-region", "patrol-path",
  "animation-layer", "cutscene-timeline", "crafting", "shop", "save-manager",
]);
for (const definition of COMPONENT_CATALOG) {
  definition.slot ??= slotForCategory(definition.category);
  definition.implementationStatus ??= EXPERIMENTAL_COMPONENTS.has(definition.type) ? "experimental" : "ready";
  definition.version ??= definition.type in Object.fromEntries(PHASE10_COMPONENTS.map((item) => [item.type, true])) ? 10 : 1;
}


const COMPONENT_DEFINITION_MAP = new Map<ComponentType, ComponentDefinition>(
  COMPONENT_CATALOG.map((definition) => [definition.type, definition]),
);

export function getComponentDefinition(type: ComponentType): ComponentDefinition {
  const definition = COMPONENT_DEFINITION_MAP.get(type);

  if (!definition) {
    throw new Error(`Unknown component type: ${type}`);
  }

  return definition;
}

export function createComponentInstance(type: ComponentType): ComponentInstance {
  const definition = getComponentDefinition(type);

  return {
    id: createId("component"),
    type,
    enabled: true,
    settings: Object.fromEntries(
      definition.settings.map((setting) => [setting.key, setting.defaultValue]),
    ),
  };
}
